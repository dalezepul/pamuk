// Birim testi: node test.cjs — tam ekran algısı ve boru iletisi doğrulaması.
const assert = require('node:assert/strict');
const { tamEkranMi, overlayAlani } = require('./pencere.cjs');
const { dogrula } = require('./yoldas.cjs');

const ekran = { x: 0, y: 0, width: 1920, height: 1080 };
const p = (r, ek = {}) => ({ h: 1, r, z: 0, i: 0, v: 1, c: 'Chrome_WidgetWin_1', ...ek });
assert.equal(tamEkranMi(p([0, 0, 1920, 1080]), ekran), true, 'ekranı tam kaplayan oyun/film');
assert.equal(tamEkranMi(p([-8, -8, 1928, 1088]), ekran), true, 'taşan kenarlıklı tam ekran');
assert.equal(tamEkranMi(p([0, 0, 1920, 1040], { z: 1 }), ekran), false, 'büyütülmüş pencere (görev çubuğu görünür) tam ekran değil');
assert.equal(tamEkranMi(p([0, 0, 1920, 1080], { z: 1 }), ekran), false, 'otomatik gizli görev çubuğunda büyütülmüş pencere');
assert.equal(tamEkranMi(p([100, 100, 900, 700]), ekran), false, 'normal pencere');
assert.equal(tamEkranMi(p([0, 0, 1920, 1080], { c: 'Progman' }), ekran), false, 'masaüstü');
assert.equal(tamEkranMi(p([0, 0, 1920, 1080], { c: 'WorkerW' }), ekran), false, 'masaüstü (WorkerW)');
assert.equal(tamEkranMi(p([0, 0, 1920, 1080], { i: 1 }), ekran), false, 'simge durumunda');
assert.equal(tamEkranMi(null, ekran), false, 'ön plan yok');
assert.equal(tamEkranMi(p([1920, 0, 3840, 1080]), ekran), false, 'ikinci ekranda tam ekran birincili etkilemez');

assert.deepEqual(dogrula({ tip: 'soru', metin: ' Devam? ', secenekler: ['Evet', 'Hayır'] }).metin, 'Devam?');
assert.throws(() => dogrula({ tip: 'kotu', metin: 'x' }));
assert.throws(() => dogrula({ tip: 'bildirim', metin: 'x'.repeat(301) }));
assert.equal(dogrula({ tip: 'soru', metin: 'x', secenekler: ['a', 'b', 'c', 'd', 'e'] }).secenekler.length, 5, '5 seçenek kabul');
assert.throws(() => dogrula({ tip: 'soru', metin: 'x', secenekler: ['a', 'b', 'c', 'd', 'e', 'f'] }), /secenekler/, '6 seçenek ret');
assert.equal(dogrula({ tip: 'soru', metin: 'x', secenekler: ['s'.repeat(40)] }).secenekler[0].length, 40, '40 karakter kabul');
assert.throws(() => dogrula({ tip: 'soru', metin: 'x', secenekler: ['s'.repeat(41)] }), /secenekler/, '41 karakter ret');
const t = dogrula({ tip: 'soru', metin: 'x', kaynak: ' claude ', konu: 'ZEPUL Site', sure: 1800 });
assert.deepEqual([t.kaynak, t.konu, t.sure], ['claude', 'ZEPUL Site', 1800]);
assert.equal(dogrula({ tip: 'bildirim', metin: 'x' }).kaynak, undefined, 'kaynak isteğe bağlı');
assert.equal(dogrula({ tip: 'bildirim', metin: 'x', kaynak: 'k'.repeat(24) }).kaynak.length, 24);
assert.throws(() => dogrula({ tip: 'bildirim', metin: 'x', kaynak: 'k'.repeat(25) }), /kaynak/, 'kaynak ≤24');
assert.throws(() => dogrula({ tip: 'bildirim', metin: 'x', kaynak: '  ' }), /kaynak/, 'boş kaynak');
assert.throws(() => dogrula({ tip: 'bildirim', metin: 'x', konu: 'k'.repeat(41) }), /konu/, 'konu ≤40');
assert.equal(dogrula({ tip: 'soru', metin: 'x', sure: 5 }).sure, 5);
for (const sure of [4, 86401, '60', NaN, -1]) assert.throws(() => dogrula({ tip: 'soru', metin: 'x', sure }), /sure/, `sure ${sure}`);
assert.equal(dogrula({ tip: 'soru', metin: 'x', sure: 0 }).sure, 0, 'soru sure 0 = süresiz');
assert.equal(dogrula({ tip: 'soru', metin: 'x', sure: 86400 }).sure, 86400);
for (const sure of [0, 4, 1801]) assert.throws(() => dogrula({ tip: 'bildirim', metin: 'x', sure }), /sure/, `bildirim sure ${sure}`);
assert.equal(dogrula({ tip: 'bildirim', metin: 'x', sure: 1800 }).sure, 1800);
assert.equal(dogrula({ tip: 'soru', metin: 'x', sira: '2/3' }).sira, '2/3');
assert.equal(dogrula({ tip: 'soru', metin: 'x' }).sira, undefined, 'sira isteğe bağlı');
for (const sira of ['2', '2/3/4', '123/4', 'a/b', 3]) assert.throws(() => dogrula({ tip: 'soru', metin: 'x', sira }), /sira/, `sira ${sira}`);
assert.deepEqual(dogrula({ tip: 'iptal', cevapKanali: 'soru:sabc123xyz0a1b2c' }), { tip: 'iptal', cevapKanali: 'soru:sabc123xyz0a1b2c' }, 'iptal metinsiz');
assert.throws(() => dogrula({ tip: 'iptal' }), /iptal/, 'iptal kanalsız');
assert.throws(() => dogrula({ tip: 'iptal', cevapKanali: 'soru:kotu' }), /iptal/, 'iptal kötü kanal');
assert.equal(dogrula({ tip: 'soru', metin: 'x', cevapKanali: 'soru:sabc123xyz0a1b2c' }).cevapKanali, 'soru:sabc123xyz0a1b2c', 'soru: öneki');
assert.equal(dogrula({ tip: 'soru', metin: 'x', cevapKanali: 'soru:sABC123xyz0a1b2c' }).cevapKanali, undefined, 'soru: büyük harf düşer');
assert.equal(dogrula({ tip: 'soru', metin: 'x', secenekler: ['a'], cevapKanali: 'zepul:z1a2b3' }).cevapKanali, 'zepul:z1a2b3', 'Zepul cevap kanalı');
assert.equal(dogrula({ tip: 'soru', metin: 'x', cevapKanali: 'http://kotu' }).cevapKanali, undefined, 'bilinmeyen kanal düşer');
assert.equal(dogrula({ tip: 'bildirim', metin: 'x', cevapKanali: 'zepul:z1a2b3' }).cevapKanali, undefined, 'bildirimde kanal yok');
assert.deepEqual(overlayAlani({ x: 0, y: 0, width: 1920, height: 1080 }), { x: 1, y: 1, width: 1918, height: 1078 }, 'overlay 1 px küçük (otomatik gizli görev çubuğu)');
console.log('test.cjs: tamam');
